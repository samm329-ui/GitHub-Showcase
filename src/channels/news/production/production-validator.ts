/**
 * Validator — hard failures reject the spec before any frame renders.
 * Warnings never block; errors always do.
 */
import { CANVAS, FPS } from "./frame-clock.js";
import { validateClip } from "./keyframe-evaluator.js";
import { audioDefinition } from "./audio-registry.js";
import type { ProductionSpec } from "./types.js";

export interface Finding { level: "error" | "warning"; message: string }

export function validateSpec(spec: ProductionSpec): Finding[] {
  const out: Finding[] = [];
  const error = (message: string) => out.push({ level: "error", message });
  const warn = (message: string) => out.push({ level: "warning", message });

  if (spec.canvas.width !== CANVAS.width || spec.canvas.height !== CANVAS.height) {
    error(`canvas must be ${CANVAS.width}x${CANVAS.height} (got ${spec.canvas.width}x${spec.canvas.height})`);
  }
  if (spec.canvas.fps !== FPS) error(`fps must be ${FPS} (got ${spec.canvas.fps})`);
  if (!Number.isInteger(spec.canvas.durationFrames) || spec.canvas.durationFrames <= 0) {
    error("canvas.durationFrames must be a positive integer frame count");
  }
  if (!spec.specVersion) error("specVersion missing");
  if (!spec.provenance) error("provenance missing");
  else {
    for (const key of ["ledgerHash", "scriptHash", "audioHash", "alignmentHash"] as const) {
      if (!/^[0-9a-f]{64}$/.test(spec.provenance[key] ?? "")) error(`provenance.${key} must be a sha256 hex digest`);
    }
    if (!["phonemes", "words", "envelope"].includes(spec.provenance.visemeSource)) {
      error("provenance.visemeSource must be phonemes | words | envelope");
    }
  }

  const sortedRoles = new Set<string>();
  for (const layer of spec.layers) {
    // Caption and graphics layers are generated by the renderer (vector text,
    // evidence lines), not loaded from disk.
    const assetOptional = layer.role === "caption" || layer.role === "graphics";
    if (!assetOptional && !layer.asset) error(`layer '${layer.id}' has no asset`);
    if (layer.asset && !layer.asset.startsWith("assets/") && !layer.asset.startsWith("assets\\")) {
      warn(`layer '${layer.id}' asset '${layer.asset}' is not under assets/ — double-check the prefix`);
    }
    if (layer.z < 0) warn(`layer '${layer.id}' has negative z (${layer.z})`);
    sortedRoles.add(layer.role);
  }
  if (spec.layers.length === 0) error("spec has no layers");
  if (!sortedRoles.has("background")) warn("no background layer");
  if (!sortedRoles.has("caption")) warn("no caption layer");

  for (const clip of spec.clips) {
    try {
      validateClip(clip.id, clip.tracks);
    } catch (error_) {
      error((error_ as Error).message);
    }
  }

  const wordCounts = new Set<string>();
  for (const block of spec.captions) {
    const startMs = block.words[0]?.startMs ?? 0;
    const endMs = block.words[block.words.length - 1]?.endMs ?? 0;
    if (endMs <= startMs) error(`caption block '${block.id}' end (${endMs}ms) must be after start (${startMs}ms)`);
    for (const word of block.words) {
      const key = `${word.word}@${word.startMs}`;
      if (wordCounts.has(key)) warn(`duplicate caption word timing '${key}'`);
      wordCounts.add(key);
      if (word.endMs <= word.startMs) error(`word '${word.word}' end ≤ start`);
      if (spec.canvas.fps && (word.endMs * spec.canvas.fps) / 1000 > spec.canvas.durationFrames) {
        error(`word '${word.word}' ends after the episode ends`);
      }
    }
  }

  for (const b of spec.boardEvents) {
    if (b.frame < 0 || b.frame >= spec.canvas.durationFrames) error(`board event '${b.id}' outside episode (frame ${b.frame})`);
    if (!b.text?.trim()) error(`board event '${b.id}' has empty text`);
  }

  for (const ev of spec.audioEvents) {
    try {
      audioDefinition(ev.name);
    } catch (error_) {
      error((error_ as Error).message);
    }
    if (ev.frame < 0 || ev.frame >= spec.canvas.durationFrames) {
      error(`audio event '${ev.id}' outside episode (frame ${ev.frame})`);
    }
  }

  return out;
}

export function isSpecValid(spec: ProductionSpec): boolean {
  return !validateSpec(spec).some(f => f.level === "error");
}
